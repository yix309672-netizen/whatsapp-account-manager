// 默认范围：未在表中的国家码使用通用 E.164 本地号码长度
export const DEFAULT_PHONE_LENGTH: [number, number] = [5, 15];

export function getPhoneLengthRange(codeWithPlus: string): [number, number] {
  const digits = codeWithPlus.replace(/[^0-9]/g, '');
  // 最长匹配优先（如 +1 240 应匹配 '1240' 而非 '1'）
  for (let len = digits.length; len > 0; len--) {
    const prefix = digits.slice(0, len);
    if (COUNTRY_PHONE_LENGTHS[prefix]) return COUNTRY_PHONE_LENGTHS[prefix];
  }
  return DEFAULT_PHONE_LENGTH;
}

export function isValidLocalNumber(codeWithPlus: string, localDigits: string): boolean {
  const [min, max] = getPhoneLengthRange(codeWithPlus);
  const len = localDigits.replace(/[^0-9]/g, '').length;
  // 全 0 号码视为无效
  if (/^0+$/.test(localDigits)) return false;
  return len >= min && len <= max;
}